  const segmenter = new Intl.Segmenter('zh-Hans', { granularity:'word' });

  function tiles(text, lessonWords) {
    // Each tile is one Chinese word; append punctuation to the preceding word.
    const source=String(text).trim();
    const chunks=[...segmenter.segment(source)].map(x=>x.segment);
    const result=[];
    for(const chunk of chunks) {
      if(!chunk.trim())continue;
      if (/^[^\p{Script=Han}\p{Script=Latin}0-9]+$/u.test(chunk)) {
        if(result.length) result[result.length-1]+=chunk;
        else result.push(chunk);
      } else result.push(chunk);
    }
    return result;
  }

  function composeFromChapter(chapter, label) {
    const lines=chapter.lines.filter(([zh,ru])=>
      !!ru && !/[“”《》]/.test(zh) && [...zh].filter(x=>/\p{Script=Han}/u.test(x)).length>=7 &&
      [...zh].filter(x=>/\p{Script=Han}/u.test(x)).length<=24 &&
      (zh.match(/。/g)||[]).length===1
    );
    const chosen=lines.sort((a,b)=>Math.abs(a[0].length-17)-Math.abs(b[0].length-17))[0]
      || chapter.lines.find(x=>x[0]&&x[1]);
    const tokens=tiles(chosen[0]);
    return {
      type:'compose', title:label, tag:'СОБЕРИ ФРАЗУ ИЗ ИСТОРИИ',
      contextZh:chapter.lines[1]?.[0]||chosen[0], contextRu:chapter.lines[1]?.[1]||chosen[1],
      prompt:chosen[1], tokens, answers:[tokens],
      hint:'Построй предложение по порядку: подлежащее, сказуемое, дополнение.',
      successZh:chosen[0], successRu:chosen[1]
    };
  }

  function branchChoice(chapter, index, prevChapter) {
    const options=chapter.decision.options.slice(0,2).map((option,i)=>({
      zh:option.zh,ru:option.ru,outcomeZh:option.resultZh,outcomeRu:option.resultRu,
      xp:20,time:i===0?-2:-4,trust:i===0?1:0,branchAt:index,branchValue:i
    }));
    const first=chapter.lines[0];
    const out={type:'choice',title:chapter.name,tag:'РЕШЕНИЕ, КОТОРОЕ ИЗМЕНИТ ИСТОРИЮ',
      contextZh:first[0],contextRu:chapter.decision.prompt+' '+first[1],options};
    if(prevChapter) out.branchContexts=prevChapter.decision.options.slice(0,2).map(o=>({
      zh:o.resultZh+' '+first[0],
      ru:o.resultRu+' '+first[1]
    }));
    return out;
  }

  function readingMissionGroups(groups,chapters) {
    const sentences=chapters.flatMap(ch=>ch.lines.map(([zh,ru])=>({zh,ru})));
    return (groups||[]).map(group=>({
      ...group,
      tasks:group.tasks.map(task=>{
        const candidates=sentences.filter(line=>line.zh.includes(task.word));
        // Every lesson word appears in its reading; avoid introducing a new unknown word in quests.
        const chosen=candidates.sort((a,b)=>a.zh.length-b.zh.length)[0];
        if(!chosen)throw Error('Chinese Lab: lesson story is missing word '+task.word);
        return {...task,sentence:chosen.zh,ru:chosen.ru};
      })
    }));
  }

  function build(lesson,chapters) {
    if(!Array.isArray(chapters)||chapters.length!==3)return lesson.quest;
    const old=lesson.quest;
    const steps=[];
    chapters.forEach((chapter,i)=>{
      steps.push(branchChoice(chapter,i,i?chapters[i-1]:null));
      steps.push(composeFromChapter(chapter,`СОБЕРИ РЕПЛИКУ · ГЛАВА ${i+1}`));
    });
    const outcomeRows=endings[lesson.id];
    if(!outcomeRows||outcomeRows.length!==4)throw Error('Missing branching endings for lesson '+lesson.id);
    return {
      ...old,
      schemaVersion:3,
      title:'ИСТОРИЯ АННЫ · '+lesson.topic,
      tagline:chapters[0].teaser,
      introZh:chapters[0].lines[0][0],
      introRu:chapters[0].lines[0][1],
      objective:'Прими три решения по ходу истории и собери три предложения на китайском. Твои ответы изменят последующие события и концовку.',
      startTime:20,
      steps,
      branchEndings:outcomeRows.map(([kicker,zh,ru])=>({kicker,zh,ru})),
      vocabMissions:readingMissionGroups(old.vocabMissions,chapters)
    };
  }

  global.ChineseLabQuestBranches=Object.freeze({build,tiles});
