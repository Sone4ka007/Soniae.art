  function build(lesson,chapters) {
    // Lessons 11+ currently use their own standalone branching quest data.
    // Do not run the legacy 1–10 chapter rewriter without mapped endings.
    if(lesson.id>10)return lesson.quest;
    if(!Array.isArray(chapters)||chapters.length!==3)return lesson.quest;
    if(lesson.id===1)return withIllustratedScenes(lesson,chapters,firstLessonQuest(lesson,chapters));
    const old=lesson.quest;
    const steps=[];
    chapters.forEach((chapter,i)=>{
      steps.push(branchChoice(chapter,i,i?chapters[i-1]:null,lesson.id));
      steps.push(composeFromChapter(chapter,`СОБЕРИ РЕПЛИКУ · ГЛАВА ${i+1}`,lesson.words.map(w=>w.hanzi)));
    });
    const outcomeRows=endings[lesson.id];
    if(!outcomeRows||outcomeRows.length!==4)throw Error('Missing branching endings for lesson '+lesson.id);
    return withIllustratedScenes(lesson,chapters,{
      ...old,
      schemaVersion:4,
      title:'ИСТОРИЯ АННЫ · '+lesson.topic,
      tagline:chapters[0].teaser,
      opening:{
        summaryRu:chapters[0].lines.slice(0,3).map(line=>line[1]).join(' '),
        panels:[
          {title:'С ЧЕГО ВСЁ НАЧАЛОСЬ',lines:chapters[0].lines.slice(0,3)},
          {title:'ПЕРВЫЕ СОБЫТИЯ',lines:chapters[0].lines.slice(3,6)}
        ]
      },
      introZh:chapters[0].lines[0][0],
      introRu:chapters[0].lines[0][1],
      objective:'Прими три решения по ходу истории и собери три предложения на китайском. Твои ответы изменят последующие события и концовку.',
      startTime:20,
      steps,
      branchEndings:outcomeRows.map(([kicker,zh,ru])=>({kicker,zh,ru})),
      vocabMissions:readingMissionGroups(old.vocabMissions,chapters)
    });
  }

